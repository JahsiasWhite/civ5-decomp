"""Classify every function in the exe: game code (in scope) vs library /
linker / compiler-generated code (out of scope).

    python tools/c5d.py scope      -> build/scope.csv + summary

Rules, first match wins:
  import_stub  6-byte `jmp [IAT]` stubs generated by the linker
  thunk        Ghidra thunk functions
  crt          byte-identical (relocations masked) to a function in the
               compiler's static libraries (msvcrt.lib, comsupp.lib, ...)
  lib_name     Ghidra Function-ID library names (ATL/MFC/CRT)
  eh_tail      compiler EH funclets: the .text tail after the last import stub
  override     ranges listed in scope_overrides.txt
  game         everything else (in scope)
"""
import csv
import hashlib
import re
import struct
import subprocess
from collections import Counter, defaultdict
from pathlib import Path

import config
from binfmt import CoffObject, PEImage

STATIC_LIBS = ["msvcrt.lib", "comsupp.lib", "comsuppw.lib", "delayimp.lib", "msvcprt.lib"]
LIB_NAME_RE = re.compile(r"^(ATL::|_AFX|CPropertySection|std::|`|_+[a-z]|@_|FID_conflict)")


def lib_signatures(ctx, work):
    """{length: [(masked_bytes, mask, name, lib)]} for functions in static libs."""
    sigs = defaultdict(list)
    work.mkdir(parents=True, exist_ok=True)
    for lib in STATIC_LIBS:
        lib_path = next((p / lib for p in ctx.libpaths if (p / lib).exists()), None)
        if not lib_path:
            continue
        r = subprocess.run([str(ctx.lib), "/nologo", "/LIST", str(lib_path)],
                           capture_output=True, text=True, env=ctx.env)
        members = [m.strip() for m in r.stdout.splitlines() if m.strip().lower().endswith(".obj")]
        out_dir = work / lib.replace(".", "_")
        out_dir.mkdir(exist_ok=True)
        for i, m in enumerate(members):
            dest = out_dir / f"{i}.obj"
            if not dest.exists():
                subprocess.run([str(ctx.lib), "/nologo", f"/EXTRACT:{m}", f"/OUT:{dest}", str(lib_path)],
                               capture_output=True, env=ctx.env)
            if not dest.exists() or dest.read_bytes()[:4] == b"\0\0\xff\xff":
                continue                      # short import object
            try:
                obj = CoffObject(dest)
            except Exception:
                continue
            for sym, sec, start, end in obj.functions():
                code = sec.data[start:end]
                if len(code) < 4:
                    continue
                mask = bytearray(len(code))
                for rel in sec.relocs:
                    if start <= rel.offset < end:
                        for k in range(rel.offset - start, min(rel.offset - start + 4, len(code))):
                            mask[k] = 1
                masked = bytes(0 if mask[k] else b for k, b in enumerate(code))
                sigs[len(code)].append((masked, bytes(mask), sym.name, lib))
    return sigs


def classify(img, funcs, ctx, build, overrides):
    imports = img.imports()
    sigs = lib_signatures(ctx, build / "libsig")
    stub_addrs = []
    result = {}
    for f in funcs:
        a, size = f["addr"], f["size"]
        code = b""
        try:
            code = img.read(a, max(size, 6))
        except ValueError:
            pass
        if size == 6 and code[:2] == b"\xff\x25" and struct.unpack_from("<I", code, 2)[0] in imports:
            result[a] = ("import_stub", imports[struct.unpack_from("<I", code, 2)[0]])
            stub_addrs.append(a)
        elif f["thunk"]:
            result[a] = ("thunk", f["name"])
    last_stub = max(stub_addrs) if stub_addrs else None

    for f in funcs:
        a, size = f["addr"], f["size"]
        if a in result:
            continue
        hit = None
        for ln, cands in ((size, sigs.get(size, ())),):
            try:
                code = img.read(a, ln)
            except ValueError:
                break
            for masked, mask, name, lib in cands:
                if all(m or c == s for c, s, m in zip(code, masked, mask)):
                    hit = f"{lib}:{name}"
                    break
        if hit:
            result[a] = ("crt", hit)
        elif not f["name"].startswith("FUN_") and LIB_NAME_RE.match(f["name"]) and not f["exported"]:
            result[a] = ("lib_name", f["name"])
        elif last_stub and a > last_stub:
            result[a] = ("eh_tail", f["name"])
        else:
            cat = next((c for lo, hi, c in overrides if lo <= a < hi), None)
            result[a] = (cat, "scope_overrides.txt") if cat else ("game", "")
    return result


def load_overrides(path):
    out = []
    if path.exists():
        for line in path.read_text().splitlines():
            line = line.split("#", 1)[0].strip()
            if line:
                lo, hi, cat = line.split()
                out.append((int(lo, 16), int(hi, 16), cat))
    return out


def run(ctx, root, build, game_exe):
    img = PEImage(game_exe)
    exports = {img.exports()[n] for n in img.exports()}
    funcs = []
    for r in config.load_functions():
        a = int(r["entry"], 16)
        size = int(r["size"])
        if r["ranges"] != "1" and int(r["min"], 16) == a:
            # Ghidra's size counts addresses across disjoint ranges (e.g.
            # switch tables); use the real extent from the entry point.
            size = int(r["max"], 16) - a + 1
        funcs.append({"addr": a, "size": size, "name": r["name"],
                      "thunk": r["thunk"] == "1", "exported": a in exports})
    res = classify(img, funcs, ctx, build, load_overrides(root / "scope_overrides.txt"))
    with open(build / "scope.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["entry", "size", "category", "detail"])
        for f in funcs:
            cat, det = res[f["addr"]]
            w.writerow([f"0x{f['addr']:08x}", f["size"], cat, det])
    n, b = Counter(), Counter()
    for f in funcs:
        n[res[f["addr"]][0]] += 1
        b[res[f["addr"]][0]] += f["size"]
    print(f"{'category':<12} {'functions':>9} {'bytes':>10}")
    for cat in sorted(n, key=lambda c: -b[c]):
        print(f"{cat:<12} {n[cat]:>9} {b[cat]:>10}")
    print(f"\nin scope (game): {n['game']} functions, {b['game']:,} bytes -> build/scope.csv")
